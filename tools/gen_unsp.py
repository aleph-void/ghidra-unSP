def gen_mul():
    sec("Multiplication: MR = r4:r3")
    emit('MulN: "16" is muln=0 { }')
    emit('MulN: muln is muln { }')
    prod = {"uu": "zext(va) * zext(vb)", "us": "zext(va) * sext(vb)", "ss": "sext(va) * sext(vb)"}
    cons = [("uu", "op0=0xe & Av!=7 & op1=0 & N=1"),
            ("us", "op0=0xf & Av!=7 & op1=0 & N<4"),
            ("ss", "op0=0xf & op1=4 & N=1")]
    for kind, pat in cons:
        emit(f':"MR =" RdV"*"RsV", {kind}" is {pat} & RdV & RsV '
             f'{{ build RdV; build RsV; local va:2 = RdV; local vb:2 = RsV; local m:4 = {prod[kind]}; '
             f'r3 = m:2; r4 = m(2); }}')
    sec("Multiply-accumulate (inner product): MR = sum([rd+i] * [rs+i]), n terms (0 means 16)")
    kinds = [("uu", "op0=0xe & (op1=2 | op1=3)"), ("us", "op0=0xf & Av!=7 & (op1=2 | op1=3)"),
             ("ss", "op0=0xf & (op1=6 | op1=7)")]
    pr = {"uu": "zext(v1) * zext(v2)", "us": "zext(v1) * sext(v2)", "ss": "sext(v1) * sext(v2)"}
    for kind, pat in kinds:
        body = ["build PtrA;", "build PtrW;", "local n:1 = muln:1;", "if (n != 0) goto <nz>;", "n = 16;", "<nz>",
                "local sum:4 = 0;", "local old:2 = 0;", "local v1:2 = 0;", "local v2:2 = 0;",
                "local a1:3 = 0;", "local a2:3 = 0;"]
        for i in range(16):
            body += ([f"if (n <= {i}) goto <done>;"] if i else []) + ["a1 = zext(PtrA);", "a2 = zext(PtrW);",
                     "v1 = *[ram]:2 a1;", "v2 = *[ram]:2 a2;", f"sum = sum + ({pr[kind]});",
                     f"if (fir_mov == 0) goto <nf{i}>;"]
            if i:
                body += ["*[ram]:2 a1 = old;"]
            body += ["old = v1;", f"<nf{i}>", "PtrA = PtrA + 1;", "PtrW = PtrW + 1;"]
        body += ["<done>", "r3 = sum:2; r4 = sum(2);"]
        emit(f':"MR =" "["PtrA"]*["PtrW"]"", {kind},"MulN is {pat} & PtrA & PtrW & muln & MulN '
             f'{{ {" ".join(body)} }}')


BITFN = ["tstb", "setb", "clrb", "invb"]


def bit_body(fn, val, bit, wr):
    """val: lvalue/varnode holding the 16 bit word, bit: expression for the bit index; wr: write-back statement
    template (or None for registers handled by caller)."""
    mask = f"(1 << ({bit}))"
    return mask


def gen_bitops():
    sec("Bit operations: tstb / setb / clrb / invb (u'nSP 1.2+, memory-absolute forms 2.0)")
    emit("# TSTB sets Z when the tested bit is clear (u'nSP 1.1 programmer's guide convention, unverified here).")
    for fi, fn in enumerate(BITFN):
        def act(target, idx):
            m = f"local m:2 = 1 << ({idx});"
            if fn == "tstb":
                return [m, f"Z_flag = ({target} & m) == 0;"]
            if fn == "setb":
                return [m, f"{target} = {target} | m;"]
            if fn == "clrb":
                return [m, f"{target} = {target} & ~m;"]
            return [m, f"{target} = {target} ^ m;"]
        # register forms: op1=0 (bit in Rs, bit3=0) / op1=1 (immediate), Av<7 (Av=7 is a jump)
        reg_t = ["local t:2 = RdV;"]
        w = ["RdW = t;"] if fn != "tstb" else []
        emit(f':{fn} RdW, RsV is op0=0xe & op1=0 & bit3=0 & bfn={fi} & RdW & RdV & RsV '
             f'{{ build RdV; build RsV; local t:2 = RdV; local k:2 = RsV & 0xf; '
             f'{" ".join(act("t", "k"))} {" ".join(w)} }}')
        emit(f':{fn} RdW, bimm is op0=0xe & op1=1 & bfn={fi} & bimm & RdW & RdV '
             f'{{ build RdV; local t:2 = RdV; local k:2 = bimm; {" ".join(act("t", "k"))} {" ".join(w)} }}')
        # memory forms: pointer is Rd; op1=4 [Rd],Rs  5 ds:[Rd],Rs  6 [Rd],imm  7 ds:[Rd],imm
        for op1, ds, imm in ((4, False, False), (5, True, False), (6, False, True), (7, True, True)):
            ptr = "(zext(ds) << 16) | zext(RdV)" if ds else "zext(RdV)"
            pdisp = '"ds:["RdV"]"' if ds else '"["RdV"]"'
            if imm:
                emit(f':{fn} {pdisp}, bimm is op0=0xe & op1={op1} & bfn={fi} & bimm & RdV '
                     f'{{ build RdV; local ad:3 = {ptr}; local t:2 = *[ram]:2 ad; local k:2 = bimm; '
                     f'{" ".join(act("t", "k"))} {"*[ram]:2 ad = t;" if fn != "tstb" else ""} }}')
            else:
                emit(f':{fn} {pdisp}, RsV is op0=0xe & op1={op1} & bit3=0 & bfn={fi} & RdV & RsV '
                     f'{{ build RdV; build RsV; local ad:3 = {ptr}; local t:2 = *[ram]:2 ad; local k:2 = RsV & 0xf; '
                     f'{" ".join(act("t", "k"))} {"*[ram]:2 ad = t;" if fn != "tstb" else ""} }}')
        # absolute memory forms (2.0): f2x0.. A odd: [imm16], ds:[imm16]
        for ds in (False, True):
            ad = "(zext(ds) << 16) | i3" if ds else "i3"
            pat = f"op0=0xf & A9=1 & A10={1 if ds else 0} & op1=1 & bfn={fi} & bimm"
            disp = ('"ds:["imm16"]"' if ds else '"["imm16"]"')
            emit(f':{fn} {disp}, bimm is ({pat}) ; imm16 '
                 f'{{ local i3:3 = imm16; local ad:3 = {ad}; local t:2 = *[ram]:2 ad; local k:2 = bimm; {" ".join(act("t", "k"))} '
                 f'{"*[ram]:2 ad = t;" if fn != "tstb" else ""} }}')


SHIFTOPS = ["asr", "asror", "lsl", "lslor", "lsr", "lsror", "rol", "ror"]


def gen_regshift():
    sec("Shifts by a register amount (u'nSP 1.3 / 2.0): semantics not documented, modelled as pcodeops")
    for k, name in enumerate(SHIFTOPS):
        op1 = 4 + (k >> 2)
        kk = k & 3
        pat = f"op0=0xe & op1={op1} & bit3=1 & bfn={kk}"
        emit(f':^RdW "=" RdD "{name}" RsV is {pat} & RdW & RdD & RdV & RsV '
             f'{{ build RdV; build RsV; RdW = {name}_op(RdV, RsV); }}')
        emit(f':^RdV "=" RdD "{name}" RsV is {pat} & Av=7 & RdD & RdV & RsV '
             f'{{ build RdV; build RsV; local res:2 = {name}_op(RdV, RsV); {goto_res()} }}')


