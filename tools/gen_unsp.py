#!/usr/bin/env python3
"""Generates data/languages/unsp.slaspec (the u'nSP SLEIGH specification).

usage: gen_unsp.py [output-file]      (default: ../data/languages/unsp.slaspec)

The ALU/addressing-mode matrix of the u'nSP is regular, so the specification is generated from
tables (one constructor per operation x addressing form) instead of being written out by hand.
Semantics follow the ISC-licensed veesem emulator (hardware-tested on the SPG200) and the
vsmile-hardware-docs notes; the decode (which encodings exist) follows MAME's unidasm output used
as a black box.  See GHIDRA-RARE.md.
"""
import os
import sys

out = []


def emit(s=""):
    out.append(s)


HEADER = r'''# Sleigh specification for u'nSP (Sunplus / Generalplus), versions 1.0 - 1.3 and the 2.0 extensions
#
# GENERATED by tools/gen_unsp.py -- edit the generator, not this file.
# Original specification: Samuel Anderson (SamuelWAnderson45/ghidra-unSP), credit @GMMan.
# Rewritten by Ghidra-Rare (see CREDITS.md and GHIDRA-RARE.md).

define endian=little;
define alignment=2;

# 22 bit address space -> size=3.  Each address accesses 16 bits (2x8) -> wordsize=2.
define space ram type=ram_space size=3 wordsize=2 default;
define space register type=register_space size=2;

# General purpose registers (bp is sometimes called r5), then the status register
define register offset=0 size=2     [ sp r1 r2 r3 r4 bp sr ];

# SR = DS[15:10] N[9] Z[8] S[7] C[6] CS[5:0]; the flags are views of the real register
define bitrange C_flag=sr[6,1] S_flag=sr[7,1] Z_flag=sr[8,1] N_flag=sr[9,1] ds=sr[10,6] cs_sr=sr[0,6];

# Program counter: the architectural PC is 16 bits plus CS (SR[5:0]); Ghidra's program counter
# is the 22 bit pc_full = CS:PC.  The alias pc is the low 16 bits, cs the high byte.
define register offset=0x15 size=3    [ pc_full ];
define register offset=0x15 size=2    [ pc ];
define register offset=0x17 size=1    [ cs ];

# Flag register (since u'nSP 1.2) and the bits the INT/IRQ/FIQ/FIR_MOV/... instructions set
define register offset=0x20 size=2    [ fr ];
define register offset=0x30 size=1    [ irqnest irq fiq fir_mov fraction sec_bank aq in_irq in_fiq ];
define register offset=0x39 size=1    [ pri sb ];

# Second bank (since u'nSP 1.2): not switched in by SECBANK (see GHIDRA-RARE.md)
define register offset=0x40 size=2  [ sr1 sr2 sr3 sr4 ];
# u'nSP 1.3 registers
define register offset=0x22 size=2  [ ss_full mds ];
# Extended registers (u'nSP 2.0)
define register offset=0x50 size=2 [ r8 r9 r10 r11 r12 r13 r14 r15 ];

define pcodeop segment;     # far-pointer userop named by unsp.pspec (never emitted in p-code)
define pcodeop exp_op;
define pcodeop divs_op;
define pcodeop divq_op;
define pcodeop asr_op;
define pcodeop asror_op;
define pcodeop lsl_op;
define pcodeop lslor_op;
define pcodeop lsr_op;
define pcodeop lsror_op;
define pcodeop rol_op;
define pcodeop ror_op;
define pcodeop mulsum_pc_op;

define token instr(16)
    op0=(12, 15)
    A=(9, 11)
    Av=(9, 11)
    A9=(9, 9)
    A10=(10, 10)
    op1=(6, 8)
    op1b=(6, 6)
    N=(3, 5)
    Nhi=(5, 5)
    Nlo=(3, 4)
    B=(0, 2)
    Bv=(0, 2)
    imm6=(0, 5)
    bfn=(4, 5)
    bimm=(0, 3) dec
    muln=(3, 6) dec
    sk=(4, 6)
    bit3=(3, 3)
    iclass=(3, 5)
    x8=(8, 8)
    x76=(6, 7)
    x54=(4, 5)
    x74=(4, 7)
;

define token instr2(16)
    imm16=(0, 15)
;

attach variables [ A B ] [ sp r1 r2 r3 r4 bp sr pc ];

# helper macros -------------------------------------------------------------------------------
# inst_start / inst_next are byte offsets (twice the word address) inside p-code.
macro pcnext(r) {            # PC as seen by the instruction: the address after the first word
    local s:3 = inst_start;
    local w:3 = s >> 1;
    r = w:2 + 1;
}
macro curcs(r) {             # CS of the current code position
    local s:3 = inst_start;
    local w:3 = s >> 17;
    local c:3 = w & 0x3f;
    r = c:2;
}
macro srnow(r) {             # SR with the code segment filled in
    local c:2;
    curcs(c);
    r = (sr & 0xffc0) | c;
}
macro pagetarget(t, v) {     # 22 bit address for a 16 bit pc value inside the current segment
    local c:2;
    curcs(c);
    local ct:3 = zext(c);
    t = (ct << 16) | zext(v);
}
macro setNZ(v) {
    N_flag = v s< 0;
    Z_flag = v == 0;
}

# register operands --------------------------------------------------------------------------------
# value of the A / B register: SR carries the live CS, PC reads as the address after the instruction
RdV: A is A & Av<6 { export A; }
RdV: A is A & Av=6 { local t:2; srnow(t); export t; }
RdV: A is A & Av=7 { local t:2; pcnext(t); export t; }
RsV: B is B & Bv<6 { export B; }
RsV: B is B & Bv=6 { local t:2; srnow(t); export t; }
RsV: B is B & Bv=7 { local t:2; pcnext(t); export t; }
# destination (Av<7); PC destinations get their own constructors
RdW: A is A & Av<7 { export A; }
RdD: A is A & Av { }
# destination register B (ds / fr moves): PC is written through the pc alias and followed
PtrW: B is B & Bv<7 { export B; }
PtrW: B is B & Bv=7 { local t:2; pcnext(t); export t; }
PtrA: A is A & Av<7 { export A; }
PtrA: A is A & Av=7 { local t:2; pcnext(t); export t; }
RsW: B is B & Bv<7 { export B; }
RsW: B is B & Bv=7 { export pc; }
PostB: is Bv<7 { }
PostB: is Bv=7 { local t:3; pagetarget(t, pc); goto [t]; }
# register B as a pointer (indirect modes, push/pop): PC reads as the next address (no write back)
'''


def sec(title):
    emit("")
    emit("# " + "-" * 90)
    emit("# " + title)


# ------------------------------------------------------------------------------------------------
# Addressing forms (the "operand" table).  Each constructor exports the value (or the memory cell).
# ------------------------------------------------------------------------------------------------
def gen_operands():
    sec("Memory operands (usable as source and destination)")
    emit('OpdBP: "[bp+"imm6"]" is op1=0 & imm6 { local ad:3 = zext(bp + imm6); export *[ram]:2 ad; }')
    emit('OpdDirect: "["imm6"]" is op1=7 & imm6 { local ad:3 = imm6; export *[ram]:2 ad; }')
    # indirect modes through B (pointer register), page 0 or DS:
    modes = [
        ('"["B"]"', 0), ('"["B"--]"', 1), ('"["B"++]"', 2), ('"[++"B"]"', 3),
        ('"ds:["B"]"', 4), ('"ds:["B"--]"', 5), ('"ds:["B"++]"', 6),
        ('"ds:[++"B"]"', 7)]
    for disp, n in modes:
        for pc in (False, True):
            cond = "Bv=7" if pc else "Bv<7"
            body = []
            ptr = "B"
            if pc:
                body.append("local ptr:2; pcnext(ptr);")
                ptr = "ptr"
            body.append("local ad:3;")
            if n == 0:
                body.append(f"ad = zext({ptr});")
            elif n == 1:
                body.append(f"ad = zext({ptr}); {ptr} = {ptr} - 1;")
            elif n == 2:
                body.append(f"ad = zext({ptr}); {ptr} = {ptr} + 1;")
            elif n == 3:
                body.append(f"{ptr} = {ptr} + 1; ad = zext({ptr});")
            elif n == 4:
                body.append(f"ad = (zext(ds) << 16) | zext({ptr});")
            elif n == 5:
                body.append(f"ad = (zext(ds) << 16) | zext({ptr}); {ptr} = {ptr} - 1; local wr:1 = {ptr} == 0xffff; ds = ds - wr;")
            elif n == 6:
                body.append(f"ad = (zext(ds) << 16) | zext({ptr}); {ptr} = {ptr} + 1; local wr:1 = {ptr} == 0; ds = ds + wr;")
            elif n == 7:
                body.append(f"{ptr} = {ptr} + 1; local wr:1 = {ptr} == 0; ds = ds + wr; ad = (zext(ds) << 16) | zext({ptr});")
            body.append("export *[ram]:2 ad;")
            emit(f"OpdInd: {disp} is op1=3 & N={n} & {cond} & B {{ {' '.join(body)} }}")
    emit('OpdM: OpdBP is OpdBP { export OpdBP; }')
    emit('OpdM: OpdInd is OpdInd { export OpdInd; }')
    emit('OpdM: OpdDirect is OpdDirect { export OpdDirect; }')

    sec("Value operands: immediate, register, shifted register")
    emit('Opd: OpdM is OpdM { export OpdM; }')
    emit('Opd: imm6 is op1=1 & imm6 { local t:2 = imm6; export t; }')
    emit('Opd: RsV is op1=4 & N=0 & RsV { export RsV; }')
    for name, op1, nhi in (("asr", 4, 1), ("lsl", 5, 0), ("lsr", 5, 1), ("rol", 6, 0), ("ror", 6, 1)):
        for cnt in range(1, 5):
            nlo = cnt - 1
            pat = f"op1={op1} & Nhi={nhi} & Nlo={nlo} & RsV"
            r = []
            if name == "asr":
                r.append("local x:4 = (sext(RsV) << 4) | zext(sb & 0xf);")
                r.append(f"x = x s>> {cnt};")
                r.append("sb = x:1 & 0xf; local t:2 = x(0) ;" if False else "sb = x:1 & 0xf; local sh:4 = x >> 4; local t:2 = sh:2;")
            elif name == "lsl":
                r.append("local x:4 = ((zext(sb & 0xf) << 16) | zext(RsV)) << %d;" % cnt)
                r.append("local sh:4 = x >> 16; sb = sh:1 & 0xf; local t:2 = x:2;")
            elif name == "lsr":
                r.append("local x:4 = ((zext(RsV) << 4) | zext(sb & 0xf)) >> %d;" % cnt)
                r.append("sb = x:1 & 0xf; local sh:4 = x >> 4; local t:2 = sh:2;")
            elif name == "rol":
                r.append("local v:4 = (zext(sb & 0xf) << 16) | zext(RsV);")
                r.append("local x:4 = ((v << %d) | (v >> %d)) & 0xfffff;" % (cnt, 20 - cnt))
                r.append("local sh:4 = x >> 16; sb = sh:1 & 0xf; local t:2 = x:2;")
            elif name == "ror":
                r.append("local v:4 = (zext(RsV) << 4) | zext(sb & 0xf);")
                r.append("local x:4 = ((v >> %d) | (v << %d)) & 0xfffff;" % (cnt, 20 - cnt))
                r.append("sb = x:1 & 0xf; local sh:4 = x >> 4; local t:2 = sh:2;")
            r.append("export t;")
            emit(f'Opd: RsV "{name}" "{cnt}" is {pat} {{ {" ".join(r)} }}')


# ------------------------------------------------------------------------------------------------
# ALU operations
# ------------------------------------------------------------------------------------------------
OPS = [(0x0, "add"), (0x1, "adc"), (0x2, "sub"), (0x3, "sbc"), (0x4, "cmp"), (0x6, "neg"),
       (0x8, "xor"), (0x9, "load"), (0xa, "or"), (0xb, "and"), (0xc, "test"), (0xd, "store")]
OPSYM = {"add": "+", "adc": "+", "sub": "-", "sbc": "-", "neg": "-", "xor": "^", "or": "|", "and": "&"}
OPASG = {"add": "+=", "adc": "+=", "sub": "-=", "sbc": "-=", "neg": "=-", "xor": "^=", "load": "=",
         "or": "|=", "and": "&="}
CARRY = ("adc", "sbc")
WRITES = ("add", "adc", "sub", "sbc", "neg", "xor", "load", "or", "and")
FLAGS_NZ_ONLY = ("neg", "xor", "load", "or", "and", "test")


def alu_body(key, va, vb):
    """p-code that computes 'res' (2 bytes) and sets the flags from the locals va, vb."""
    if key == "add":
        return [f"local res:2 = {va} + {vb};", f"C_flag = carry({va}, {vb});", "setNZ(res);",
                f"S_flag = N_flag ^ scarry({va}, {vb});"]
    if key == "adc":
        return ["local cin:4 = zext(C_flag);", f"local t:4 = zext({va}) + zext({vb}) + cin;",
                f"local ts:4 = sext({va}) + sext({vb}) + cin;", "local res:2 = t:2;", "C_flag = t[16,1];",
                "setNZ(res);", "S_flag = ts s< 0;"]
    if key in ("sub", "cmp"):
        return [f"local res:2 = {va} - {vb};", f"C_flag = {vb} <= {va};", "setNZ(res);",
                f"S_flag = {va} s< {vb};"]
    if key == "sbc":
        return ["local cin:4 = zext(C_flag);", f"local nb:2 = ~{vb};",
                f"local t:4 = zext({va}) + zext(nb) + cin;", f"local ts:4 = sext({va}) + sext(nb) + cin;",
                "local res:2 = t:2;", "C_flag = t[16,1];", "setNZ(res);", "S_flag = ts s< 0;"]
    if key == "neg":
        return [f"local res:2 = -{vb};", "setNZ(res);"]
    if key == "xor":
        return [f"local res:2 = {va} ^ {vb};", "setNZ(res);"]
    if key == "or":
        return [f"local res:2 = {va} | {vb};", "setNZ(res);"]
    if key in ("and", "test"):
        return [f"local res:2 = {va} & {vb};", "setNZ(res);"]
    if key == "load":
        return [f"local res:2 = {vb};", "setNZ(res);"]
    raise ValueError(key)


def goto_res():
    return "local tgt:3; pagetarget(tgt, res); goto [tgt];"


def carry_sfx(key):
    return '", carry"' if key in CARRY else ""


def gen_alu():
    sec("ALU operations, one-word forms: rd op= operand")
    emit("# op1<2 with Av=7 is a conditional jump (below)")
    for op0, key in OPS:
        if key == "store":
            for opd, extra in (("OpdBP", " & Av!=7"), ("OpdInd", ""), ("OpdDirect", "")):
                emit(f':^{opd} "=" RdV is op0={op0:#x} & RdV & {opd}{extra} '
                     f'{{ build {opd}; build RdV; {opd} = RdV; }}')
            continue
        if key in WRITES:
            body = " ".join(["build Opd;", "build RdV;", "local va:2 = RdV;", "local vb:2 = Opd;"] +
                            alu_body(key, "va", "vb") + ["RdW = res;"])
            emit(f':^RdW "{OPASG[key]}" Opd{carry_sfx(key)} is op0={op0:#x} & RdW & RdV & Opd {{ {body} }}')
            # PC destination: no flags, jump (Av=7 with op1<2 is a conditional jump instead)
            # flags are not touched when the destination is PC: separate body without them
            body = " ".join(["build Opd;", "build RdV;", "local va:2 = RdV;", "local vb:2 = Opd;"] +
                            [l for l in alu_nf(key, "va", "vb")] + [goto_res()])
            emit(f':^RdV "{OPASG[key]}" Opd{carry_sfx(key)} is op0={op0:#x} & Av=7 & RdV & Opd '
                 f'{{ {body} }}')
        else:
            body = " ".join(["build Opd;", "build RdV;", "local va:2 = RdV;", "local vb:2 = Opd;"] +
                            alu_body(key, "va", "vb"))
            emit(f':{key} RdV, Opd is op0={op0:#x} & RdV & Opd & (Av!=7 | op1>1) {{ {body} }}')


def alu_nf(key, va, vb):
    """Same result computation without flag updates (PC destination)."""
    if key == "add":
        return [f"local res:2 = {va} + {vb};"]
    if key == "adc":
        return [f"local res:2 = {va} + {vb} + zext(C_flag);"]
    if key == "sub":
        return [f"local res:2 = {va} - {vb};"]
    if key == "sbc":
        return [f"local res:2 = {va} + ~{vb} + zext(C_flag);"]
    if key == "neg":
        return [f"local res:2 = -{vb};"]
    if key == "xor":
        return [f"local res:2 = {va} ^ {vb};"]
    if key == "or":
        return [f"local res:2 = {va} | {vb};"]
    if key == "and":
        return [f"local res:2 = {va} & {vb};"]
    if key == "load":
        return [f"local res:2 = {vb};"]
    raise ValueError(key)


# ------------------------------------------------------------------------------------------------
# Two-word forms: rd = rs op imm16 / [imm16], [imm16] = rs op rd
# ------------------------------------------------------------------------------------------------
REGN = ["sp", "r1", "r2", "r3", "r4", "bp", "sr", "pc"]


def gen_alu16():
    sec("ALU operations, two-word forms (op1=4, N=1..3)")
    emit("# N=1: rd = rs op imm16     N=2: rd = rs op [imm16]     N=3: [imm16] = rs op rd")
    emit("# neg / cmp / test (and the load / store forms of N=3) exist only with rd = rs.")
    for op0, key in OPS:
        for n in (1, 2, 3):
            if key == "store" and n != 3:
                continue
            if n == 3 and key in ("cmp", "test"):
                continue
            same = key in ("neg", "cmp", "test") or (n == 3 and key in ("load", "store"))
            for k in (range(8) if same else [None]):
                regpat = f" & Av={k} & Bv={k}" if same else ""
                base = f"op0={op0:#x} & op1=4 & N={n}{regpat}"
                if n in (1, 2):
                    mem = n == 2
                    od = '"["imm16"]"' if mem else "imm16"
                    rd_pre = ["build RdV;", "build RsV;", "local va:2 = RsV;"]
                    rd_pre += ["local ma:3 = imm16;", "local vb:2 = *[ram]:2 ma;"] if mem else ["local vb:2 = imm16;"]
                    if key in ("cmp", "test"):
                        body = " ".join(rd_pre + alu_body(key, "va", "vb"))
                        emit(f':{key} RsV, {od} is ({base} & RdV & RsV) ; imm16 {{ {body} }}')
                        continue
                    sym = OPSYM.get(key)
                    if key == "load":
                        disp = f'"=" {od}'
                    elif key == "neg":
                        disp = f'"=" "-" {od}'
                    else:
                        disp = f'"=" RsV "{sym}" {od}{carry_sfx(key)}'
                    # destination Av<7 (flags) or Av=7 (jump, no flags)
                    if k != 7:
                        body = " ".join(rd_pre + alu_body(key, "va", "vb") + ["RdW = res;"])
                        emit(f':^RdW {disp} is ({base} & RdW & RdV & RsV) ; imm16 {{ {body} }}')
                    if k in (None, 7):
                        body = " ".join(rd_pre + alu_nf(key, "va", "vb") + [goto_res()])
                        base7 = base + (" & Av=7" if k is None else "")
                        emit(f':^RdV {disp} is ({base7} & RdV & RsV) ; imm16 {{ {body} }}')
                else:
                    pre = ["build RdV;", "build RsV;", "local va:2 = RsV;", "local vb:2 = RdV;", "local ma:3 = imm16;"]
                    if key in ("load", "store"):
                        bl = ["local res:2 = vb;"] + (["setNZ(res);"] if key == "load" else [])
                        disp = '"["imm16"]" "=" RdV'
                    elif key == "neg":
                        bl = ["local res:2 = -vb;", "setNZ(res);"]
                        disp = '"["imm16"]" "=" "-" RdV'
                    else:
                        bl = alu_body(key, "va", "vb") if k != 7 else alu_nf(key, "va", "vb")
                        disp = f'"["imm16"]" "=" RsV "{OPSYM[key]}" RdV{carry_sfx(key)}'
                    body = " ".join(pre + bl + ["*[ram]:2 ma = res;"])
                    pc_split = "" if same else (" & Av!=7",) 
                    if same:
                        emit(f':{disp} is ({base} & RdV & RsV) ; imm16 {{ {body} }}')
                    else:
                        emit(f':{disp} is ({base} & Av!=7 & RdV & RsV) ; imm16 {{ {body} }}')
                        bl = alu_nf(key, "va", "vb")
                        body = " ".join(pre + bl + ["*[ram]:2 ma = res;"])
                        emit(f':{disp} is ({base} & Av=7 & RdV & RsV) ; imm16 {{ {body} }}')


def alu_nf(key, va, vb):
    """Same result computation without flag updates (PC destination)."""
    return {
        "add": [f"local res:2 = {va} + {vb};"],
        "adc": [f"local res:2 = {va} + {vb} + zext(C_flag);"],
        "sub": [f"local res:2 = {va} - {vb};"],
        "sbc": [f"local res:2 = {va} + ~{vb} + zext(C_flag);"],
        "neg": [f"local res:2 = -{vb};"],
        "xor": [f"local res:2 = {va} ^ {vb};"],
        "or": [f"local res:2 = {va} | {vb};"],
        "and": [f"local res:2 = {va} & {vb};"],
        "load": [f"local res:2 = {vb};"],
    }[key]


# ------------------------------------------------------------------------------------------------
# Branches, stack, calls
# ------------------------------------------------------------------------------------------------
CONDS = [(0x0, "jb", "C_flag == 0"), (0x1, "jae", "C_flag == 1"), (0x2, "jge", "S_flag == 0"),
         (0x3, "jl", "S_flag == 1"), (0x4, "jne", "Z_flag == 0"), (0x5, "je", "Z_flag == 1"),
         (0x6, "jpl", "N_flag == 0"), (0x7, "jmi", "N_flag == 1"),
         (0x8, "jbe", "(Z_flag == 1) || (C_flag == 0)"), (0x9, "ja", "(Z_flag == 0) && (C_flag == 1)"),
         (0xa, "jle", "(Z_flag == 1) || (S_flag == 1)"), (0xb, "jg", "(Z_flag == 0) && (S_flag == 0)"),
         (0xc, "jvc", "N_flag == S_flag"), (0xd, "jvs", "N_flag != S_flag"), (0xe, "jmp", None)]


def gen_branches():
    sec("Jumps: PC-relative, 6 bit displacement (Av=7, op1=0 forward, op1=1 backward)")
    emit("RelP6: addr is imm6 [ addr = inst_next + imm6; ] { export *[ram]:3 addr; }")
    emit("RelN6: addr is imm6 [ addr = inst_next - imm6; ] { export *[ram]:3 addr; }")
    for op0, name, cond in CONDS:
        for op1, rel in ((0, "RelP6"), (1, "RelN6")):
            body = f"if ({cond}) goto {rel};" if cond else f"goto {rel};"
            emit(f':{name} {rel} is op0={op0:#x} & Av=7 & op1={op1} & {rel} {{ {body} }}')


def rd_reg(i, tmp):
    if i == 6:
        return f"srnow({tmp});"
    if i == 7:
        return f"pcnext({tmp});"
    return f"{tmp} = {REGN[i]};"


def gen_stack():
    sec("PUSH / POP (op1=2) and returns")
    emit("# push Rlo, Rhi to [Rs]: stores Rhi first, post-decrement; pop restores Rlo..Rhi with pre-increment.")
    emit("# POP of SR and PC is a far return; PC alone returns inside the current segment.")
    for n in range(8):
        for a in range(8):
            if n <= a + 1 and not (a == 7 and n == 0):
                regs = [a - i for i in range(n)]
                body = ["build PtrW;", "local v:2;", "local ad:3;"]
                for r in regs:
                    body += [rd_reg(r, "v"), "ad = zext(PtrW);", "*[ram]:2 ad = v;", "PtrW = PtrW - 1;"]
                first = REGN[a - n + 1] if n else REGN[(a + 1) % 8]
                emit(f':push "{first}, {REGN[a]}" "to" "["PtrW"]" is op0=0xd & op1=2 & Av={a} & N={n} & PtrW '
                     f'{{ {" ".join(body)} }}')
            if a + n <= 7 and not (a == 7 and n == 0):
                regs = [a + 1 + i for i in range(n)]
                body = ["build PtrW;", "local ad:3;"]
                for r in regs:
                    body += ["PtrW = PtrW + 1;", "ad = zext(PtrW);"]
                    body += ["pc = *[ram]:2 ad;" if r == 7 else f"{REGN[r]} = *[ram]:2 ad;"]
                if 7 in regs:
                    if 6 in regs:
                        body += ["local tgt:3 = (zext(cs_sr) << 16) | zext(pc);", "return [tgt];"]
                    else:
                        body += ["local tgt:3; pagetarget(tgt, pc);", "return [tgt];"]
                first = REGN[(a + 1) % 8]
                last = REGN[a + n] if n else REGN[a]
                extra = " & Bv!=0" if (a, n) == (5, 2) else ""
                emit(f':pop "{first}, {last}" "from" "["PtrW"]" is op0=0x9 & op1=2 & Av={a} & N={n} & PtrW{extra} '
                     f'{{ {" ".join(body)} }}')
    body = ["sp = sp + 1;", "local ad:3 = zext(sp);", "sr = *[ram]:2 ad;", "sp = sp + 1;", "ad = zext(sp);",
            "pc = *[ram]:2 ad;", "local tgt:3 = (zext(cs_sr) << 16) | zext(pc);"]
    emit(f':retf is op0=0x9 & op1=2 & Av=5 & N=2 & Bv=0 {{ {" ".join(body)} return [tgt]; }}')
    emit(f':reti is op0=0x9 & op1=2 & Av=5 & N=3 & Bv=0 {{ {" ".join(body)} '
         f'if (in_fiq == 0) goto <lirq>; in_fiq = 0; goto <ldone>; <lirq> in_irq = 0; <ldone> return [tgt]; }}')


